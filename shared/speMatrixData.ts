export function slugifyMatrixSeries(seriesName: string): string {
  return seriesName
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export function getSpeMatrixSeries(seriesSlug: string): SpeMatrixSeries | undefined {
  const normalized = seriesSlug.toLowerCase();
  return SPE_MATRIX_SERIES.find((series) => slugifyMatrixSeries(series.seriesName) === normalized);
}
